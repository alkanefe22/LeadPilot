/** Shared by pnpm eval and pnpm eval:scenarios: an isolated DB, built-in adapters, git commit. */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { PGlite } from "@electric-sql/pglite";
import { drizzle } from "drizzle-orm/pglite";
import { migrate } from "drizzle-orm/pglite/migrator";
import type { Adapters } from "../src/server/adapters";
import { MockCalendarAdapter } from "../src/server/adapters/calendar/mock";
import { InternalCrmAdapter } from "../src/server/adapters/crm/internal";
import { ConsoleEmailAdapter } from "../src/server/adapters/email/console";
import type { Database } from "../src/server/db/client";
import * as schema from "../src/server/db/schema";
import { ensureDefaultWorkspace } from "../src/server/db/seed-lib";

/** Fresh in-memory Postgres with all migrations and the default workspace. */
export async function freshDb(): Promise<Database> {
  const client = new PGlite();
  const db = drizzle(client, { schema }) as unknown as Database;
  await migrate(drizzle(client), { migrationsFolder: path.resolve("src/server/db/migrations") });
  await ensureDefaultWorkspace(db, "whsec_eval");
  return db;
}

/** Built-in calendar / CRM / email: evals never touch real providers. */
export function builtInAdapters(): Adapters {
  return {
    calendar: new MockCalendarAdapter(),
    crm: new InternalCrmAdapter(),
    email: new ConsoleEmailAdapter(() => {}),
  };
}

export function gitCommit(): string {
  try {
    return execSync("git rev-parse --short HEAD").toString().trim();
  } catch {
    return "unknown";
  }
}

/** Replaces the generated block between <!-- MARKER:START --> and <!-- MARKER:END --> in README.md. */
export function replaceReadmeBlock(marker: string, body: string, generator = "pnpm eval") {
  const file = "README.md";
  const readme = readFileSync(file, "utf8");
  const start = `<!-- ${marker}:START -->`;
  const end = `<!-- ${marker}:END -->`;
  const a = readme.indexOf(start);
  const b = readme.indexOf(end);
  if (a < 0 || b < 0) {
    console.warn(`README markers ${marker} not found — skipping README update.`);
    return;
  }
  const block = `${start}\n<!-- Generated by \`${generator}\` — do not edit by hand. -->\n\n${body}\n${end}`;
  writeFileSync(file, readme.slice(0, a) + block + readme.slice(b + end.length));
}
